import { useCallback, useEffect, useMemo, useState } from "react";
import { api, deploymentKey, embeddedData } from "./api";
import type { DashboardData } from "./types";
import { formatDate } from "./format";
import { readStorage, useHashRoute, writeStorage } from "./hooks";
import { EmptyState } from "./components/Feedback";
import { Overview } from "./views/Overview";
import { DeploymentView, TAB_IDS, type TabId } from "./views/DeploymentView";

type Theme = "light" | "dark" | "";

function applyTheme(theme: Theme) {
  const root = document.documentElement;
  if (theme) root.setAttribute("data-theme", theme);
  else root.removeAttribute("data-theme");
}

function ThemeToggle() {
  const [theme, setTheme] = useState<Theme>(() => {
    const saved = readStorage("pskit-theme");
    return saved === "light" || saved === "dark" ? saved : "";
  });
  useEffect(() => applyTheme(theme), [theme]);
  const next = () => {
    const dark =
      theme === "dark" || (!theme && window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
    const value: Theme = dark ? "light" : "dark";
    setTheme(value);
    writeStorage("pskit-theme", value);
  };
  return (
    <button type="button" className="btn btn-ghost" onClick={next} title="Toggle light/dark theme" aria-label="Toggle theme">
      ◐
    </button>
  );
}

export function App() {
  const [data, setData] = useState<DashboardData>(() => embeddedData());
  const [live, setLive] = useState(false);
  const [route, navigate] = useHashRoute();

  const refresh = useCallback(async () => {
    const fresh = await api.probe();
    if (fresh) {
      setData(fresh);
      setLive(true);
    }
    return fresh;
  }, []);

  // Live mode: the page is served by `pskit dashboard --serve`. Refresh the deployment list periodically.
  useEffect(() => {
    let timer: number | undefined;
    let stopped = false;
    const loop = async () => {
      const fresh = await refresh();
      if (!stopped && fresh) timer = window.setTimeout(loop, 30000);
    };
    loop();
    return () => {
      stopped = true;
      window.clearTimeout(timer);
    };
  }, [refresh]);

  const [key, rawTab] = route.split("/");
  const tab: TabId = (TAB_IDS as readonly string[]).includes(rawTab) ? (rawTab as TabId) : "functions";
  const selected = useMemo(() => data.deployments.find((d) => deploymentKey(d) === key), [data, key]);

  const services = Array.from(new Set(data.deployments.map((d) => d.service))).filter(Boolean);
  useEffect(() => {
    if (selected) document.title = `${selected.service} · ${selected.stage} — pskit`;
  }, [selected]);

  return (
    <div className="app">
      <header className="topbar">
        <div className="topbar-inner">
          <button type="button" className="brand" onClick={() => navigate("")}>
            <span className="logo" aria-hidden="true">
              λ
            </span>
            <span>
              <b>{services.length ? services.join(" / ") : "Serverless"}</b>
              <small>py-serverless-kit dashboard</small>
            </span>
          </button>
          <div className="topbar-right">
            <span className={live ? "mode mode-live" : "mode"} title={live ? "Connected to pskit dashboard --serve" : "Static snapshot"}>
              {live ? "● Live" : "Snapshot"}
            </span>
            <ThemeToggle />
          </div>
        </div>
      </header>
      <main className="content">
        {key && !selected ? (
          <EmptyState title="Deployment not found">
            <button type="button" className="btn" onClick={() => navigate("")}>
              Back to all deployments
            </button>
          </EmptyState>
        ) : selected ? (
          <DeploymentView
            deployment={selected}
            deploymentKey={deploymentKey(selected)}
            live={live}
            tab={tab}
            onTab={(t) => navigate(`${deploymentKey(selected)}/${t}`)}
            onBack={() => navigate("")}
          />
        ) : (
          <Overview deployments={data.deployments} onOpen={(k) => navigate(k)} />
        )}
      </main>
      <footer className="footer muted">
        {data.generated_at ? `Generated ${formatDate(data.generated_at)}` : "Not generated by pskit"} · py-serverless-kit
      </footer>
    </div>
  );
}
