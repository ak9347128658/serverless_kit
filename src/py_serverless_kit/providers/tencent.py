"""Tencent Cloud: SCF + API Gateway + timer / COS triggers."""

from __future__ import annotations

import json
import re
import shutil
from typing import Any, Dict, List, Optional

from ..config.schema import FunctionConfig, ServiceConfig
from ..runtime.adapters.base import envelope
from . import schedule as sched
from .base import HTTP, SCHEDULE, STORAGE, Issue, Provider, RenderContext
from .terraform_doc import TerraformDoc, escape, ref, tf_id

FUNCTION = "tencentcloud_scf_function"
_BUCKET_RE = re.compile(r"^[a-z0-9][a-z0-9-]*-\d+$")


def _gateway_path(path: str) -> str:
    """API Gateway has no greedy params; ``/files/{p+}`` becomes prefix ``/files``."""
    segments = [s for s in path.split("/") if s]
    if segments and segments[-1].endswith("+}"):
        segments = segments[:-1]
    return "/" + "/".join(segments)


class TencentProvider(Provider):
    name = "tencent"
    display_name = "Tencent Cloud SCF"
    tier = "beta"
    terraform_source = "tencentcloudstack/tencentcloud"
    terraform_version = ">= 1.81.0"
    terraform_local_name = "tencentcloud"
    default_region = "ap-guangzhou"
    capabilities = frozenset({HTTP, SCHEDULE, STORAGE})
    max_name_length = 60
    name_pattern = r"[^a-z0-9_-]"
    runtimes = {"python3.9": "Python3.9", "python3.10": "Python3.10"}
    vendor_dependencies = True
    max_timeout = 900
    notes = (
        "HTTP via an API Gateway service (one API per route, released to `release`); "
        "timer and COS triggers; COS bucket names must include the APPID suffix (name-1250000000)."
    )

    # ------------------------------------------------------------------ bundle
    def shim_files(self, config: ServiceConfig) -> Dict[str, str]:
        return {
            "index.py": (
                "# Generated by py-serverless-kit. SCF handler: index.main_handler\n"
                "from py_serverless_kit.runtime.adapters.tencent import main_handler  # noqa: F401\n"
            )
        }

    def provider_block(self, ctx: RenderContext) -> Dict[str, Any]:
        block: Dict[str, Any] = {"region": ctx.region}
        if ctx.opt("profile"):
            block["profile"] = ctx.opt("profile")
        return block

    def physical_name(self, service: str, stage: str, logical: str) -> str:
        name = super().physical_name(service, stage, logical)
        # SCF names must start with a letter and must not end with '-' or '_'.
        return name.rstrip("-_") or "fn"

    def extra_validation(self, config: ServiceConfig) -> List[Issue]:
        issues = []
        if config.provider.iam.statements:
            issues.append(
                Issue(
                    "warning",
                    "iam.statements are not translated to CAM policies on Tencent; set iam.role to an existing "
                    "CAM role name",
                    "provider.iam",
                )
            )
        for name, fn in config.functions.items():
            where = f"functions.{name}"
            for ev in fn.events_of("http"):
                if ev.auth != "none":
                    issues.append(
                        Issue("error", f"http auth `{ev.auth}` is not supported on Tencent (use none)", where)
                    )
                if ev.method == "PATCH":
                    issues.append(Issue("error", "Tencent API Gateway does not support PATCH; use ANY", where))
            for ev in fn.events_of("storage"):
                if not _BUCKET_RE.match(ev.bucket):
                    issues.append(
                        Issue(
                            "error",
                            f"COS bucket {ev.bucket!r} must be '<name>-<APPID>', e.g. uploads-1250000000",
                            where,
                        )
                    )
            memory = config.memory_of(fn)
            if memory not in (64, 128) and memory % 128 != 0:
                issues.append(
                    Issue("error", f"SCF memory must be 64, 128 or a multiple of 128 MB (got {memory})", where)
                )
        return issues

    # ------------------------------------------------------------------ render
    def render_resources(self, doc: TerraformDoc, ctx: RenderContext) -> None:
        cfg = ctx.config
        zip_name = self._artifact_copy(ctx)
        fn_out: Dict[str, Dict[str, Any]] = {}
        service: Optional[str] = None
        apis: List[str] = []
        for name, fn in ctx.function_items():
            res = self._function(doc, ctx, name, fn, zip_name)
            namespace = ctx.opt("namespace", "default")
            out: Dict[str, Any] = {
                "id": ref(res, "name"),
                "console": "https://console.cloud.tencent.com/scf/list-detail"
                f"?ns={namespace}&id={ctx.physical_name(name)}",
            }
            http_events = fn.events_of("http")
            if http_events:
                service = service or self._service(doc, ctx)
                apis.extend(self._apis(doc, ctx, service, name, res, fn, http_events))
                out["base_url"] = "https://" + ref(service, "outer_sub_domain") + "/release"
            fn_out[name] = out

        endpoint = None
        if service:
            doc.resource(
                "tencentcloud_api_gateway_service_release",
                "release",
                {
                    "service_id": ref(service, "id"),
                    "environment_name": "release",
                    "release_desc": f"py-serverless-kit {ctx.artifact.sha256[:12]}",
                    "depends_on": apis,
                },
            )
            endpoint = "https://" + ref(service, "outer_sub_domain") + "/release"

        wf_out = {n: {"id": ref(FUNCTION, tf_id(f"{n}-orchestrator"), "name")} for n in sorted(cfg.workflows)}
        doc.output(
            "pskit",
            {"functions": fn_out, "workflows": wf_out, "endpoint": endpoint},
            description="py-serverless-kit deployment summary",
        )

    # ------------------------------------------------------------------ pieces
    @staticmethod
    def _artifact_copy(ctx: RenderContext) -> str:
        """SCF only re-uploads when ``zip_file`` *path* changes, so use a content-addressed copy."""
        name = f"artifact-{ctx.artifact.sha256[:16]}.zip"
        target = ctx.work_dir / name
        for old in ctx.work_dir.glob("artifact-*.zip"):
            if old.name != name:
                old.unlink()
        if not target.exists() and ctx.artifact.path.exists():
            shutil.copyfile(ctx.artifact.path, target)
        return name

    def _function(self, doc: TerraformDoc, ctx: RenderContext, name: str, fn: FunctionConfig, zip_name: str) -> str:
        cfg = ctx.config
        triggers: List[Dict[str, Any]] = []
        configs: List[Dict[str, Any]] = []
        for i, ev in enumerate(fn.events_of("schedule")):
            tname = re.sub(r"[^A-Za-z0-9_-]", "-", ev.name or f"timer-{i}")[:100]
            desc = "0 " + sched.named_cron5(ev) + " *"
            triggers.append({"name": tname, "type": "timer", "trigger_desc": desc})
            if ev.input is not None or not ev.enabled:
                configs.append(
                    {
                        "trigger_name": tname,
                        "type": "timer",
                        "trigger_desc": desc,
                        "enable": "OPEN" if ev.enabled else "CLOSE",
                        "custom_argument": escape(json.dumps(envelope("schedule", ev.input, source="tencent.timer"))),
                    }
                )
        for ev in fn.events_of("storage"):
            label = f"b-{ev.bucket}"
            if not ev.existing and not doc.has_resource("tencentcloud_cos_bucket", label):
                doc.resource(
                    "tencentcloud_cos_bucket", label, {"bucket": ev.bucket, "acl": "private", "tags": ctx.tags()}
                )
            for action in ev.events:
                desc_obj: Dict[str, Any] = {
                    "event": {"created": "cos:ObjectCreated:*", "deleted": "cos:ObjectRemove:*"}[action]
                }
                if ev.prefix or ev.suffix:
                    desc_obj["filter"] = {"Prefix": ev.prefix or "", "Suffix": ev.suffix or ""}
                triggers.append(
                    {
                        "name": f"{ev.bucket}.cos.{ctx.region}.myqcloud.com",
                        "type": "cos",
                        "cos_region": ctx.region,
                        "trigger_desc": json.dumps(desc_obj),
                    }
                )
        body: Dict[str, Any] = {
            "name": ctx.physical_name(name),
            "description": re.sub(r"[^\w\s,.一-鿿]", " ", fn.description)[:1000],
            "handler": "index.main_handler",
            "runtime": self.runtime_id(cfg.runtime_of(fn)),
            "mem_size": cfg.memory_of(fn),
            "timeout": cfg.timeout_of(fn),
            "namespace": ctx.opt("namespace", "default"),
            "zip_file": "${path.module}/" + zip_name,
            "enable_public_net": True,
            "environment": {k: escape(v) for k, v in ctx.environment(name, fn).items()},
            "tags": ctx.tags(fn),
        }
        if triggers:
            body["triggers"] = triggers
        role = fn.iam.role or cfg.provider.iam.role
        if role:
            body["role"] = role
        body.update(fn.options)  # escape hatch: vpc_id, subnet_id, layers, cls_*...
        res = doc.resource(FUNCTION, name, body)
        for c in configs:
            doc.resource(
                "tencentcloud_scf_trigger_config",
                f"{name}-{c['trigger_name']}",
                {"function_name": ref(res, "name"), "namespace": ref(res, "namespace"), **c},
            )
        return res

    def _service(self, doc: TerraformDoc, ctx: RenderContext) -> str:
        return doc.resource(
            "tencentcloud_api_gateway_service",
            "http",
            {
                "service_name": re.sub(r"[^A-Za-z0-9_]", "_", ctx.prefix)[:50],
                "protocol": "http&https",
                "service_desc": f"py-serverless-kit {ctx.service} ({ctx.stage})",
                "net_type": ["OUTER"],
                "ip_version": "IPv4",
                "tags": ctx.tags(),
            },
        )

    def _apis(
        self,
        doc: TerraformDoc,
        ctx: RenderContext,
        service: str,
        name: str,
        fn_res: str,
        fn: FunctionConfig,
        events: List[Any],
    ) -> List[str]:
        refs = []
        for i, ev in enumerate(events):
            path = _gateway_path(ev.path)
            params = re.findall(r"\{([A-Za-z_]\w*)\}", path)
            body: Dict[str, Any] = {
                "service_id": ref(service, "id"),
                "api_name": re.sub(r"[^A-Za-z0-9_]", "_", f"{name}_{i}")[:60],
                "api_desc": f"{ev.method} {ev.path} -> {name}",
                "auth_type": "NONE",
                "protocol": "HTTP",
                "enable_cors": ev.cors_config is not None,
                "request_config_path": path,
                "request_config_method": ev.method,
                "service_config_type": "SCF",
                "service_config_scf_function_name": ref(fn_res, "name"),
                "service_config_scf_function_namespace": ref(fn_res, "namespace"),
                "service_config_scf_function_qualifier": "$LATEST",
                "service_config_scf_is_integrated_response": True,
                "service_config_timeout": min(ctx.config.timeout_of(fn), 1800),
                "response_type": "JSON",
            }
            if params:
                body["request_parameters"] = [
                    {"name": p, "position": "PATH", "type": "string", "required": True, "desc": p} for p in params
                ]
            refs.append(doc.resource("tencentcloud_api_gateway_api", f"{name}-{i}", body))
        return refs
