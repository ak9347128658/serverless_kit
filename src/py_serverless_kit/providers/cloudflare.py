"""Cloudflare Workers, one Worker script per function, in Python (Pyodide) or JavaScript.

Python: each Worker is uploaded as a single Python module. pskit generates that
module (``.pskit/cloudflare-<stage>/cloudflare/<fn>.py``) by embedding every
``.py`` file of the bundle - your code plus the pskit runtime - and installing
an import hook that serves them from memory. That keeps your project layout
(packages, relative imports) working without a multi-module upload.

Node.js / TypeScript: :meth:`CloudflareProvider.shim_files` writes one ES module entry per
function (``_pskit_cf/<fn>.mjs``) that statically imports the handler modules, the
manifest and the JS adapter. The builder bundles each entry with esbuild into
``_pskit_cf/<fn>.bundle.mjs`` (:meth:`node_bundle_entries`), which is uploaded as the
Worker's main module with the ``nodejs_compat`` flag. Environment variables are
``plain_text`` bindings that the adapter exposes as ``process.env``.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..config.schema import ServiceConfig
from . import schedule as sched
from .base import HTTP, SCHEDULE, Issue, Provider, ProviderError, RenderContext
from .terraform_doc import TerraformDoc, escape, ref

SCRIPT = "cloudflare_workers_script"
WORKER_DIR = "cloudflare"
DEFAULT_COMPAT_DATE = "2025-09-01"
NODE_ENTRY_DIR = "_pskit_cf"
# Node.js built-ins the Workers runtime provides with nodejs_compat (compatibility_date >= 2025-09-01).
NODE_BUILTINS = ("assert", "buffer", "crypto", "events", "fs", "path", "stream", "string_decoder", "url", "util")
REQUIRE_SHIM = f"{NODE_ENTRY_DIR}/require_shim.mjs"


def require_shim_source() -> str:
    """Give CommonJS code in the bundle a ``require()`` for the built-ins (an ES module bundle has none).

    esbuild (``--platform=node --format=esm``) turns ``require("crypto")`` into a call that falls back
    to a global ``require`` at run time; this module, imported first, defines it.
    """
    lines = ["// Generated by py-serverless-kit - do not edit. require() for Node.js built-ins on Workers."]
    for i, name in enumerate(NODE_BUILTINS):
        lines.append(f'import * as b{i} from "node:{name}";')
    table = ", ".join(f"{json.dumps(name)}: b{i}" for i, name in enumerate(NODE_BUILTINS))
    lines += [
        f"const builtins = {{ {table} }};",
        "if (typeof globalThis.require === \"undefined\") {",
        "  globalThis.require = (id) => {",
        "    const name = String(id).replace(/^node:/, \"\");",
        "    if (Object.prototype.hasOwnProperty.call(builtins, name)) return builtins[name];",
        "    throw new Error(`require(${JSON.stringify(id)}) is not available on Cloudflare Workers`);",
        "  };",
        "}",
    ]
    return "\n".join(lines) + "\n"


def handler_module(handler: str) -> str:
    """``src.handlers.hello`` -> ``src/handlers`` (resolved by esbuild: .ts/.js or folder index)."""
    return handler.replace(":", ".").rsplit(".", 1)[0].replace(".", "/")


def node_entry_source(config: ServiceConfig, function: str) -> str:
    """ES module entry of one Worker; esbuild bundles it with everything it imports."""
    js = json.dumps
    modules = sorted({handler_module(fn.handler) for fn in config.functions.values()})
    fn = config.functions[function]
    schedules = {sched.to_cron5(ev): ev.input for ev in fn.events_of("schedule") if ev.enabled}
    lines = [
        "// Generated by py-serverless-kit - do not edit. Cloudflare Worker entry (bundled with esbuild).",
        'import "./require_shim.mjs";',
        'import manifest from "../pskit_manifest.json";',
        'import * as adapter from "../pskit_runtime/adapters/cloudflare.js";',
    ]
    names = {}
    for i, mod in enumerate(modules):
        names[mod] = f"m{i}"
        lines.append(f'import * as m{i} from "../{mod}";')
    registry = ", ".join(f"{js(mod.replace('/', '.'))}: {names[mod]}" for mod in modules)
    lines += [
        "",
        f"export default adapter.worker({{ function: {js(function)}, manifest, "
        f"schedules: {js(schedules, sort_keys=True)}, modules: {{ {registry} }} }});",
    ]
    return "\n".join(lines) + "\n"

_LOADER = '''\
import importlib.abc
import importlib.util
import json
import sys

_PSKIT_ROOT = "/pskit_bundle"


class _PskitImporter(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    """Serves the embedded bundle modules from memory."""

    def __init__(self, files):
        self._modules = {}
        for path, source in files.items():
            if not path.endswith(".py"):
                continue
            name = path[:-3].replace("/", ".")
            is_pkg = name == "__init__" or name.endswith(".__init__")
            if is_pkg:
                name = name[: -len(".__init__")] if "." in name else ""
            if name:
                self._modules[name] = (path, source, is_pkg)
        for name in list(self._modules):
            parts = name.split(".")
            for i in range(1, len(parts)):
                parent = ".".join(parts[:i])
                if parent not in self._modules:  # implicit namespace package
                    self._modules[parent] = ("/".join(parts[:i]) + "/__init__.py", "", True)

    def find_spec(self, fullname, path=None, target=None):
        entry = self._modules.get(fullname)
        if entry is None:
            return None
        return importlib.util.spec_from_loader(
            fullname, self, origin=_PSKIT_ROOT + "/" + entry[0], is_package=entry[2]
        )

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        path, source, is_pkg = self._modules[module.__spec__.name]
        module.__file__ = _PSKIT_ROOT + "/" + path
        if is_pkg:
            module.__path__ = [_PSKIT_ROOT + "/" + path.rsplit("/", 1)[0]]
        exec(compile(source, module.__file__, "exec"), module.__dict__)


sys.meta_path.insert(0, _PskitImporter(_PSKIT_FILES))

from py_serverless_kit.runtime import manifest as _pskit_manifest  # noqa: E402
from py_serverless_kit.runtime.adapters import cloudflare as _pskit_cf  # noqa: E402

_pskit_manifest.set_manifest(
    _pskit_manifest.BundleManifest.from_dict(json.loads(_PSKIT_FILES["pskit_manifest.json"]))
)
_pskit_cf.configure(_PSKIT_FUNCTION, _PSKIT_ENV, _PSKIT_SCHEDULES)

from workers import WorkerEntrypoint  # noqa: E402


class Default(WorkerEntrypoint):
    async def fetch(self, request):
        return await _pskit_cf.fetch(request, getattr(self, "env", None))

    async def scheduled(self, controller, env=None, ctx=None):
        return await _pskit_cf.scheduled(controller, env if env is not None else getattr(self, "env", None))
'''


def embedded_files(build_dir: Path) -> tuple[Dict[str, str], List[str]]:
    """Collect ``.py`` files and the manifest from the bundle; report skipped files."""
    files: Dict[str, str] = {}
    skipped: List[str] = []
    for path in sorted(p for p in build_dir.rglob("*") if p.is_file()):
        rel = path.relative_to(build_dir).as_posix()
        if "__pycache__" in rel or rel == "requirements.txt":
            continue
        if rel.endswith(".py") or rel == "pskit_manifest.json":
            files[rel] = path.read_text("utf-8")
        else:
            skipped.append(rel)
    return files, skipped


def worker_source(files: Dict[str, str], function: str, env: Dict[str, str], schedules: Dict[str, Any]) -> str:
    lines = [
        "# Generated by py-serverless-kit - do not edit. Cloudflare Python Worker entry module.",
        f"_PSKIT_FUNCTION = {function!r}",
        f"_PSKIT_ENV = {dict(sorted(env.items()))!r}",
        f"_PSKIT_SCHEDULES = {json.loads(json.dumps(schedules))!r}",
        "_PSKIT_FILES = {",
    ]
    for rel, source in files.items():
        lines.append(f"    {rel!r}: {source!r},")
    lines.append("}")
    return "\n".join(lines) + "\n\n" + _LOADER


class CloudflareProvider(Provider):
    name = "cloudflare"
    display_name = "Cloudflare Workers"
    tier = "experimental"
    terraform_source = "cloudflare/cloudflare"
    terraform_version = ">= 5.28, < 6.0"
    default_region = ""
    capabilities = frozenset({HTTP, SCHEDULE})
    max_name_length = 63
    name_pattern = r"[^a-z0-9_-]"
    runtimes = {f"python3.{v}": f"python3.{v}" for v in (11, 12, 13)}
    # Workers run JavaScript natively; the version is the Workers runtime (nodejs_compat), not a Node.js release.
    node_runtimes = {f"nodejs{v}": f"nodejs{v}" for v in (18, 20, 22)}
    vendor_dependencies = False
    node_bundle = True
    # One ES module per Worker; built-ins stay external and are served by _pskit_cf/require_shim.mjs.
    node_bundle_options = ["--platform=node", "--format=esm", "--target=es2022"]
    max_timeout = 900
    notes = (
        "Node.js/TypeScript Workers are bundled with esbuild (dependencies included, nodejs_compat). "
        "Python Workers run on Pyodide: only the standard library and Pyodide built-in packages are available "
        "(requirements.txt is NOT bundled). One Worker per function; http via workers.dev (set "
        "options.workers_subdomain for URLs) or options.zone_id + functions.<fn>.options.route; schedules via "
        "Cron Triggers. Needs options.account_id and CLOUDFLARE_API_TOKEN."
    )

    # ------------------------------------------------------------------ bundle
    def shim_files(self, config: ServiceConfig) -> Dict[str, str]:
        if config.language == "node":
            files = {f"{NODE_ENTRY_DIR}/{name}.mjs": node_entry_source(config, name) for name in sorted(config.functions)}
            files[REQUIRE_SHIM] = require_shim_source()
            return files
        return {}  # the Python entry module is generated per function in render_resources

    def node_package(self, config: ServiceConfig) -> Dict[str, Any]:
        """Fields merged into the bundled package.json of a Node.js service (none: esbuild bundles)."""
        return {}

    def node_bundle_entries(self, config: ServiceConfig) -> Dict[str, str]:
        """``{bundled output: entry}`` (paths relative to the build dir) for the builder's esbuild step.

        Each output must be one ES module: ``esbuild --bundle --format=esm --platform=node --target=es2022``
        (built-ins stay external; ``require_shim.mjs``, imported first by every entry, serves them).
        """
        return {
            f"{NODE_ENTRY_DIR}/{name}.bundle.mjs": f"{NODE_ENTRY_DIR}/{name}.mjs" for name in sorted(config.functions)
        }

    def provider_block(self, ctx: RenderContext) -> Dict[str, Any]:
        return {}

    def region(self, config: ServiceConfig) -> str:
        return config.provider.region or ""

    def extra_validation(self, config: ServiceConfig) -> List[Issue]:
        issues: List[Issue] = []
        if not config.provider.options.get("account_id"):
            issues.append(Issue("error", "options.account_id is required", "provider.options.account_id"))
        if config.language == "node":
            if config.package.node.bundle is False:
                issues.append(
                    Issue("error", "Workers need one bundled module per Worker; remove package.node.bundle: false", "package")
                )
        else:
            issues.append(
                Issue(
                    "warning",
                    "Cloudflare Python Workers only provide the standard library and Pyodide built-in packages; "
                    "dependencies from requirements.txt are not bundled",
                    "package",
                )
            )
        for name, fn in config.functions.items():
            for ev in fn.events_of("http"):
                if ev.auth != "none":
                    issues.append(
                        Issue(
                            "error",
                            f"auth `{ev.auth}` is not supported on Workers; validate tokens "
                            "in the handler or use Cloudflare Access",
                            f"functions.{name}",
                        )
                    )
            if fn.options.get("route") and not config.provider.options.get("zone_id"):
                issues.append(Issue("error", "options.route needs provider.options.zone_id", f"functions.{name}"))
        return issues

    # ------------------------------------------------------------------ render
    def _node_script(
        self, ctx: RenderContext, name: str, fn: Any, out_dir: Path, account: str, script_name: str
    ) -> Dict[str, Any]:
        build = ctx.artifact.build_dir
        bundled = Path(build) / NODE_ENTRY_DIR / f"{name}.bundle.mjs" if build is not None else None
        if bundled is None or not bundled.is_file():
            raise ProviderError(
                f"Cloudflare: the esbuild bundle for {name!r} is missing ({NODE_ENTRY_DIR}/{name}.bundle.mjs); "
                "run `pskit package` with Node.js and npm on PATH"
            )
        data = bundled.read_bytes()
        (out_dir / f"{name}.mjs").write_bytes(data)
        bindings = [
            {"name": key, "type": "plain_text", "text": escape(value)}
            for key, value in sorted(ctx.environment(name, fn).items())
        ]
        return {
            "account_id": account,
            "script_name": script_name,
            "content_file": f"${{path.module}}/{WORKER_DIR}/{name}.mjs",
            "content_sha256": hashlib.sha256(data).hexdigest(),
            "content_type": "application/javascript+module",
            "main_module": "worker.mjs",
            "compatibility_date": str(ctx.opt("compatibility_date", DEFAULT_COMPAT_DATE)),
            "compatibility_flags": ["nodejs_compat"],
            "bindings": bindings,
        }

    def render_resources(self, doc: TerraformDoc, ctx: RenderContext) -> None:
        cfg = ctx.config
        account = str(ctx.opt("account_id", ""))
        subdomain = ctx.opt("workers_subdomain")
        workers_dev = bool(ctx.opt("workers_dev", True))
        build = ctx.artifact.build_dir
        node = cfg.language == "node"
        files, skipped = embedded_files(Path(build)) if build is not None and not node else ({}, [])
        if skipped:
            doc.warnings.append(
                "Cloudflare: non-Python files are not uploaded: "
                + ", ".join(skipped[:10])
                + (" ..." if len(skipped) > 10 else "")
            )
        out_dir = ctx.work_dir / WORKER_DIR
        out_dir.mkdir(parents=True, exist_ok=True)

        fn_out: Dict[str, Dict[str, Any]] = {}
        endpoint: Optional[str] = None
        for name, fn in ctx.function_items():
            script_name = ctx.physical_name(name)
            schedules = {sched.to_cron5(ev): ev.input for ev in fn.events_of("schedule") if ev.enabled}
            if node:
                body = self._node_script(ctx, name, fn, out_dir, account, script_name)
            else:
                source = worker_source(files, name, ctx.environment(name, fn), schedules)
                path = out_dir / f"{name}.py"
                path.write_bytes(source.encode("utf-8"))
                body = {
                    "account_id": account,
                    "script_name": script_name,
                    "content_file": f"${{path.module}}/{WORKER_DIR}/{name}.py",
                    "content_sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
                    "content_type": "text/x-python",
                    "main_module": "worker.py",
                    "compatibility_date": str(ctx.opt("compatibility_date", DEFAULT_COMPAT_DATE)),
                    "compatibility_flags": ["python_workers"],
                }
            opts = dict(fn.options)
            route = opts.pop("route", None)
            body.update(opts)
            script = doc.resource(SCRIPT, name, body)
            http = bool(fn.events_of("http"))
            if http and workers_dev:
                doc.resource(
                    "cloudflare_workers_script_subdomain",
                    name,
                    {"account_id": account, "script_name": ref(script, "script_name"), "enabled": True},
                )
            if route:
                doc.resource(
                    "cloudflare_workers_route",
                    name,
                    {"zone_id": str(ctx.opt("zone_id", "")), "pattern": route, "script": ref(script, "script_name")},
                )
            if schedules:
                doc.resource(
                    "cloudflare_workers_cron_trigger",
                    name,
                    {
                        "account_id": account,
                        "script_name": ref(script, "script_name"),
                        "schedules": [{"cron": c} for c in schedules],
                    },
                )
            out: Dict[str, Any] = {
                "id": ref(script, "script_name"),
                "console": f"https://dash.cloudflare.com/{account}/workers/services/view/{script_name}/production",
            }
            url = None
            if http and workers_dev and subdomain:
                url = f"https://{script_name}.{subdomain}.workers.dev"
            elif http and route:
                url = "https://" + str(route).rstrip("*").rstrip("/")
            if url:
                out["url"] = url
                out["base_url"] = url
                endpoint = endpoint or url
            fn_out[name] = out
        wf_out = {n: {"id": ctx.physical_name(f"{n}-orchestrator")} for n in cfg.workflows}
        doc.output(
            "pskit",
            {"functions": fn_out, "workflows": wf_out, "endpoint": endpoint},
            description="py-serverless-kit deployment summary",
        )
