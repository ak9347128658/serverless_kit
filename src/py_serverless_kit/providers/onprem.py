_CTL = """\
# Generated by py-serverless-kit. Starts and stops the on-premises host.
import os
import shutil
import signal
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def _stop_previous():
    # Stop the running host before replacing app/. On Windows a live process
    # locks that directory and the swap fails.
    pidfile = ROOT / "host.pid"
    if not pidfile.is_file():
        return
    try:
        pid = int(pidfile.read_text("ascii").strip() or "0")
    except ValueError:
        pid = 0
    if pid > 0:
        if sys.platform == "win32":
            subprocess.call(
                ["taskkill", "/PID", str(pid), "/T", "/F"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
        else:
            try:
                os.kill(pid, signal.SIGTERM)
            except OSError:
                pass
    try:
        pidfile.unlink()
    except OSError:
        pass


def _long(path):
    # Windows: vendored packages nest deeply; an extended path lifts the 260-character limit.
    if sys.platform == "win32" and not str(path).startswith("\\\\\\\\?\\\\"):
        return "\\\\\\\\?\\\\" + str(Path(path).resolve())
    return str(path)


def _activate():
    staging = ROOT / "staging"
    app = ROOT / "app"
    if not staging.is_dir():
        return
    _stop_previous()
    if app.exists():
        shutil.rmtree(_long(app))
    try:
        staging.rename(app)
    except OSError:
        shutil.copytree(_long(staging), _long(app))
        shutil.rmtree(_long(staging), ignore_errors=True)


if (ROOT / "staging").is_dir():
    _activate()
if not (ROOT / "app").is_dir():
    sys.stderr.write("on-prem bundle is missing under %s\\n" % ROOT)
    raise SystemExit(1)
sys.path.insert(0, str(ROOT / "app"))
from py_serverless_kit.runtime.onprem_host import main

if __name__ == "__main__":
    raise SystemExit(main(ROOT))
"""

