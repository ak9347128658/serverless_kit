"""On-premises provider.

``pskit deploy --provider onprem`` writes a self-contained host next to the
Terraform configuration and starts it with a built-in ``terraform_data``
provisioner (no cloud plugin, no extra broker to install).

HTTP is served by that process. Schedule, queue, storage and topic triggers
use directories the host creates on startup (``use: builtin``). Point a service
at a directory you already run with ``use: directory`` and ``path``. Workflows
run on the embedded engine inside the same process, so they are not capped by
a cloud function timeout.

``terraform.extra`` resources that belong to another cloud (``aws_*``, ...) are
omitted: this configuration does not configure those providers. The warning
names each one.
"""

from __future__ import annotations

import copy
import hashlib
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from ..config.schema import ServiceConfig
from ..runtime.cron import CronError, next_cron, resolve_zone
from .base import HTTP, QUEUE, SCHEDULE, STORAGE, TOPIC, Issue, Provider, RenderContext
from .terraform_doc import TerraformDoc

APP_DIR = "onprem_app"
_SERVICE_KINDS = ("schedule", "queue", "storage", "topic", "workflow")
_FOREIGN_PREFIXES = (
    "aws_",
    "google_",
    "azurerm_",
    "alicloud_",
    "tencentcloud_",
    "huaweicloud_",
    "oci_",
    "ibm_",
    "digitalocean_",
    "cloudflare_",
)
_CTL = """\
# Generated by py-serverless-kit. Starts and stops the on-premises host.
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "app"))
from py_serverless_kit.runtime.onprem_host import main

if __name__ == "__main__":
    raise SystemExit(main(ROOT))
"""


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def _quote(value: str) -> str:
    return '"' + value.replace('"', "") + '"'


def _endpoint(host: str, port: int, advertise: Optional[str]) -> str:
    if advertise:
        return str(advertise).rstrip("/")
    shown = "127.0.0.1" if host in ("0.0.0.0", "::", "[::]") else host  # noqa: S104
    if ":" in shown and not shown.startswith("["):
        shown = "[" + shown + "]"
    return f"http://{shown}:{port}"


def _safe_name(value: str, what: str) -> Optional[str]:
    text = str(value)
    if not text or text in (".", "..") or "/" in text or "\\" in text:
        return f"invalid {what} name {value!r}"
    return None


class OnPremProvider(Provider):
    name = "onprem"
    display_name = "On-premises"
    tier = "experimental"
    terraform_source = "terraform.io/builtin/terraform"
    default_region = "local"
    capabilities = frozenset({HTTP, SCHEDULE, QUEUE, STORAGE, TOPIC})
    max_name_length = 63
    runtimes = {f"python3.{minor}": f"python3.{minor}" for minor in (9, 10, 11, 12, 13, 14)}
    vendor_dependencies = True
    # Zoneinfo on Windows reads this package. It is pure data and is imported
    # by the stdlib, so the host can honour schedule timezones without a system copy.
    extra_requirements = ["tzdata"]
    max_timeout = 3600
    warn_on_embedded_workflow = False
    notes = (
        "Runs a long-lived Python process on this machine (the same interpreter that "
        "runs `pskit deploy`). HTTP, schedules, file-backed queues, directory storage, "
        "topics and embedded workflows all run in that process. No extra broker is "
        "required. Set provider.options.services.<kind> to `builtin` (deploy it) or "
        "`{use: directory, path: ...}` to use a directory you already have. "
        "`pskit remove` stops the process and leaves the data directory in place."
    )

    def pip_platform(self, runtime: str, architecture: str) -> List[str]:
        # Dependencies run on this machine, not in a Linux cloud image.
        del runtime, architecture
        return []

    def init_doc(self, ctx: RenderContext) -> TerraformDoc:
        doc = TerraformDoc()
        doc.required_version(ctx.config.provider.terraform.required_version)
        state = ctx.config.provider.state
        if state.backend:
            doc.backend(state.backend, state.config)
        return doc

    def provider_block(self, ctx: RenderContext) -> Optional[Dict[str, Any]]:
        return None

    def shim_files(self, config: ServiceConfig) -> Dict[str, str]:
        return {
            "onprem_handler.py": (
                "# Generated by py-serverless-kit. On-premises entry: main(event, context)\n"
                "from py_serverless_kit.runtime.adapters.onprem import main  # noqa: F401\n"
            )
        }

    def extra_validation(self, config: ServiceConfig) -> List[Issue]:
        issues: List[Issue] = []
        options = config.provider.options
        known = {"host", "port", "advertise", "data_dir", "services", "poll_seconds", "admin_token"}
        for key in options:
            if key not in known:
                issues.append(Issue("warning", f"unknown option {key!r} is ignored", f"provider.options.{key}"))
        port = options.get("port", 8080)
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            issues.append(Issue("error", "options.port must be an integer from 1 to 65535", "provider.options.port"))
        host = options.get("host", "127.0.0.1")
        if not isinstance(host, str) or not host.strip():
            issues.append(Issue("error", "options.host must be a bind address", "provider.options.host"))
        poll = options.get("poll_seconds", 0.5)
        if isinstance(poll, bool) or not isinstance(poll, (int, float)) or poll <= 0:
            issues.append(
                Issue("error", "options.poll_seconds must be a positive number", "provider.options.poll_seconds")
            )
        token = options.get("admin_token")
        if token is not None and not isinstance(token, str):
            issues.append(Issue("error", "options.admin_token must be a string", "provider.options.admin_token"))
        running = f"python{sys.version_info.major}.{sys.version_info.minor}"
        if config.provider.runtime != running:
            issues.append(
                Issue(
                    "warning",
                    f"the host runs with this interpreter ({running}), not {config.provider.runtime}. "
                    "Use the same Python for `pskit deploy` and the functions.",
                    "provider.runtime",
                )
            )
        try:
            self._services(config, Path("."))
        except ValueError as exc:
            issues.append(Issue("error", str(exc), "provider.options.services"))
        for name, fn in config.functions.items():
            for ev in fn.events_of("http"):
                if ev.auth != "none":
                    issues.append(
                        Issue(
                            "error",
                            f"auth `{ev.auth}` is not enforced on-premises; use auth: none and check tokens in the handler",
                            f"functions.{name}",
                        )
                    )
            for ev in fn.events_of("schedule"):
                if ev.cron:
                    zone = resolve_zone(ev.timezone)
                    if zone is None:
                        issues.append(
                            Issue(
                                "warning",
                                f"timezone {ev.timezone} needs the IANA database; `pskit deploy` vendors tzdata. "
                                "Until then this schedule is evaluated in UTC.",
                                f"functions.{name}",
                            )
                        )
                    try:
                        next_cron(ev.cron, datetime.now(timezone.utc))
                    except CronError as exc:
                        issues.append(Issue("error", str(exc), f"functions.{name}"))
            for kind, label in (("queue", "name"), ("topic", "name"), ("storage", "bucket")):
                for ev in fn.events_of(kind):
                    bad = _safe_name(getattr(ev, label), kind)
                    if bad:
                        issues.append(Issue("error", bad, f"functions.{name}"))
                    dead = getattr(ev, "dead_letter", None)
                    if dead:
                        bad_dead = _safe_name(dead, "dead_letter queue")
                        if bad_dead:
                            issues.append(Issue("error", bad_dead, f"functions.{name}"))
        dropped = _foreign_names(config.provider.terraform.extra)
        if dropped:
            issues.append(
                Issue(
                    "warning",
                    "on-premises deploy does not load other cloud providers, so these terraform.extra "
                    f"resources are omitted: {', '.join(dropped)}. Move a replacement under "
                    "providers.onprem.terraform.extra, or keep this file on its original provider.",
                    "provider.terraform.extra",
                )
            )
        backend = config.provider.state.backend
        if backend in ("s3", "gcs", "azurerm"):
            issues.append(
                Issue(
                    "warning",
                    f"state backend `{backend}` still points at a cloud. On a machine without that backend, "
                    "set provider.state.backend empty (or override it under providers.onprem) to keep state local.",
                    "provider.state",
                )
            )
        return issues

    def _services(self, config: ServiceConfig, root: Path) -> Dict[str, Dict[str, Any]]:
        raw = config.provider.options.get("services") or {}
        if not isinstance(raw, dict):
            raise ValueError("options.services must be a mapping of schedule/queue/storage/topic/workflow")
        unknown = sorted(set(raw) - set(_SERVICE_KINDS))
        if unknown:
            raise ValueError(f"unknown services {unknown}; expected {', '.join(_SERVICE_KINDS)}")
        data_dir = self._data_dir(config, root)
        resolved = {
            "schedule": {"use": "builtin"},
            "queue": {"use": "builtin", "path": str(data_dir / "queues")},
            "storage": {"use": "builtin", "path": str(data_dir / "buckets")},
            "topic": {"use": "builtin", "path": str(data_dir / "topics")},
            "workflow": {"use": "embedded"},
        }
        for kind, body in raw.items():
            use, path = self._binding(kind, body, root)
            item: Dict[str, Any] = {"use": use}
            if path is not None:
                item["path"] = str(path)
            elif kind in ("queue", "storage", "topic"):
                item["path"] = resolved[kind]["path"]
            resolved[kind] = item
        return resolved

    def _data_dir(self, config: ServiceConfig, root: Path) -> Path:
        raw = config.provider.options.get("data_dir")
        if not raw:
            path = root / ".pskit" / "onprem-data" / f"{config.service}-{config.provider.stage}"
        else:
            path = Path(str(raw))
            if not path.is_absolute():
                path = root / path
        return path

    def _binding(self, kind: str, body: Any, root: Path) -> Tuple[str, Optional[Path]]:
        if isinstance(body, str):
            body = {"use": body}
        if not isinstance(body, dict):
            raise ValueError(f"services.{kind} must be `builtin` or a mapping with `use`")
        use = str(body.get("use") or "builtin")
        if kind == "schedule" and use != "builtin":
            raise ValueError("services.schedule only supports `builtin` (the host runs the scheduler)")
        if kind == "workflow" and use not in ("embedded", "builtin"):
            raise ValueError("services.workflow only supports `embedded`")
        if kind == "workflow" and use == "builtin":
            use = "embedded"
        if kind in ("queue", "storage", "topic") and use not in ("builtin", "directory"):
            raise ValueError(f"services.{kind}.use must be `builtin` (deployed with the host) or `directory`")
        path = body.get("path")
        if use == "directory":
            if not path:
                raise ValueError(f"services.{kind}.path is required when use is directory")
            target = Path(str(path))
            if not target.is_absolute():
                target = root / target
            return use, target
        if path:
            target = Path(str(path))
            if not target.is_absolute():
                target = root / target
            return use, target
        return use, None

    def _spec(self, ctx: RenderContext) -> Dict[str, Any]:
        cfg = ctx.config
        options = cfg.provider.options
        host = str(options.get("host") or "127.0.0.1")
        port = int(options.get("port") or 8080)
        advertise = options.get("advertise")
        endpoint = _endpoint(host, port, str(advertise) if advertise else None)
        services = self._services(cfg, ctx.root)
        functions: Dict[str, Any] = {}
        for name, fn in ctx.function_items():
            events = []
            for ev in fn.events:
                body = ev.config.model_dump(mode="json")
                body["type"] = ev.type
                if ev.type == "queue" and body.get("visibility_timeout") is None:
                    body["visibility_timeout"] = max(30, 6 * cfg.timeout_of(fn))
                events.append(body)
            functions[name] = {
                "handler": fn.handler,
                "timeout": cfg.timeout_of(fn),
                "environment": ctx.environment(name, fn),
                "events": events,
            }
        return {
            "service": cfg.service,
            "stage": cfg.provider.stage,
            "region": ctx.region or "local",
            "host": host,
            "port": port,
            "endpoint": endpoint,
            "data_dir": str(self._data_dir(cfg, ctx.root)),
            "poll_seconds": float(options.get("poll_seconds") or 0.5),
            "admin_token": str(options.get("admin_token") or ""),
            "services": services,
            "functions": functions,
        }

    def write_project(self, ctx: RenderContext, spec: Dict[str, Any]) -> str:
        root = ctx.work_dir / APP_DIR
        staging = root / "staging"
        if staging.exists():
            shutil.rmtree(staging)
        root.mkdir(parents=True, exist_ok=True)
        build = ctx.artifact.build_dir
        if build is not None and Path(build).is_dir():
            shutil.copytree(build, staging)
        else:  # pragma: no cover - the packager always sets build_dir
            staging.mkdir(parents=True)
        text = json.dumps(spec, indent=2, sort_keys=True) + "\n"
        _write(root / "pskit_host.json", text)
        _write(root / "onprem_ctl.py", _CTL)
        return hashlib.sha256(text.encode("utf-8")).hexdigest()

    def render_resources(self, doc: TerraformDoc, ctx: RenderContext) -> None:
        spec = self._spec(ctx)
        digest = self.write_project(ctx, spec)
        python = _quote(sys.executable)
        doc.resource(
            "terraform_data",
            "host",
            {
                "triggers_replace": [ctx.artifact.sha256, digest],
                "input": {"endpoint": spec["endpoint"]},
                "provisioner": [
                    {"local-exec": {"working_dir": "${path.module}/" + APP_DIR, "command": f"{python} onprem_ctl.py start"}},
                    {
                        "local-exec": {
                            "when": "destroy",
                            "working_dir": "${path.module}/" + APP_DIR,
                            "command": f"{python} onprem_ctl.py stop",
                        }
                    },
                ],
            },
        )
        endpoint = spec["endpoint"]
        fn_out: Dict[str, Any] = {}
        for name, fn in ctx.function_items():
            http = bool(fn.events_of("http"))
            item: Dict[str, Any] = {
                "id": ctx.physical_name(name),
                "url": endpoint if http else None,
                "console": endpoint + "/__pskit/health",
            }
            if http:
                item["base_url"] = endpoint
            fn_out[name] = item
        wf_out = {}
        for name in ctx.config.workflows:
            wf_out[name] = {"id": ctx.physical_name(f"{name}-orchestrator"), "url": f"{endpoint}/workflows/{name}"}
        doc.output(
            "pskit",
            {
                "functions": fn_out,
                "workflows": wf_out,
                "endpoint": endpoint,
                "services": spec["services"],
            },
            description="py-serverless-kit on-premises deployment",
        )
        extra, dropped = _without_foreign(ctx.config.provider.terraform.extra)
        for name in dropped:
            doc.warnings.append(
                f"omitted terraform.extra resource `{name}` (on-premises does not configure that cloud provider)"
            )
        if extra:
            doc.merge(extra)

    def render(self, ctx: RenderContext) -> TerraformDoc:
        # init_doc has no provider plugin. User extra is filtered in render_resources.
        doc = self.init_doc(ctx)
        self.render_resources(doc, ctx)
        return doc


def _foreign_names(extra: Any) -> List[str]:
    if not isinstance(extra, dict):
        return []
    resources = extra.get("resource")
    if not isinstance(resources, dict):
        return []
    return sorted(name for name in resources if str(name).startswith(_FOREIGN_PREFIXES))


def _without_foreign(extra: Any) -> Tuple[Dict[str, Any], List[str]]:
    if not isinstance(extra, dict) or not extra:
        return {}, []
    cleaned = copy.deepcopy(extra)
    dropped = _foreign_names(cleaned)
    resources = cleaned.get("resource")
    if isinstance(resources, dict):
        for name in dropped:
            resources.pop(name, None)
        if not resources:
            cleaned.pop("resource", None)
    if dropped and isinstance(cleaned.get("output"), dict):
        outputs = cleaned["output"]
        for key, value in list(outputs.items()):
            text = json.dumps(value)
            if any(name in text for name in dropped):
                outputs.pop(key, None)
        if not outputs:
            cleaned.pop("output", None)
    return cleaned, dropped
