    def extra_validation(self, config: ServiceConfig) -> List[Issue]:
        issues: List[Issue] = []
        options = config.provider.options
        issues.extend(self._smtp_validation(config))
        known = {
            "host",
            "port",
            "advertise",
            "data_dir",
            "services",
            "poll_seconds",
            "admin_token",
            "deploy",
            "env_file",
        }
        known |= set(_TUNING)
        for key, (kind, low) in _TUNING.items():
            if key not in options:
                continue
            value = options[key]
            if kind == "int" and (isinstance(value, bool) or not isinstance(value, int) or value < low):
                issues.append(Issue("error", f"options.{key} must be an integer >= {low}", f"provider.options.{key}"))
            if kind == "bool" and not isinstance(value, bool):
                issues.append(Issue("error", f"options.{key} must be true or false", f"provider.options.{key}"))
            if kind == "level" and str(value).upper() not in ("DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"):
                issues.append(
                    Issue("error", f"options.{key} must be DEBUG, INFO, WARNING or ERROR", f"provider.options.{key}")
                )
        for key in options:
            if key not in known:
                issues.append(Issue("warning", f"unknown option {key!r} is ignored", f"provider.options.{key}"))
        port = options.get("port", 8080)
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            issues.append(Issue("error", "options.port must be an integer from 1 to 65535", "provider.options.port"))
        host = options.get("host", "127.0.0.1")
        if not isinstance(host, str) or not host.strip():
            issues.append(Issue("error", "options.host must be a bind address", "provider.options.host"))
        poll = options.get("poll_seconds", 0.5)
        if isinstance(poll, bool) or not isinstance(poll, (int, float)) or poll <= 0:
            issues.append(
                Issue("error", "options.poll_seconds must be a positive number", "provider.options.poll_seconds")
            )
        token = options.get("admin_token")
        if token is not None and not isinstance(token, str):
            issues.append(Issue("error", "options.admin_token must be a string", "provider.options.admin_token"))
        env_file = options.get("env_file")
        if env_file is not None and (not isinstance(env_file, str) or not env_file.strip()):
            issues.append(Issue("error", "options.env_file must be a file path", "provider.options.env_file"))
        try:
            spec = parse_deploy(
                options,
                service=config.service,
                stage=config.provider.stage,
                runtime=config.provider.runtime,
                architecture=config.provider.architecture,
            )
        except ValueError as exc:
            issues.append(Issue("error", str(exc), "provider.options.deploy"))
            spec = None
        if spec is not None:
            missing = validate_identity(spec)
            if missing:
                where = (
                    "provider.options.deploy.pem"
                    if targets_remote_docker(spec)
                    else "provider.options.deploy.identity_file"
                )
                issues.append(Issue("warning", missing, where))
            if targets_remote_docker(spec) and spec.install_docker and not spec.sudo:
                issues.append(
                    Issue(
                        "warning",
                        "installing Docker on the server uses sudo unless the SSH user is root. "
                        "Set options.deploy.sudo: true.",
                        "provider.options.deploy.sudo",
                    )
                )
            node = config.language == "node"
            if node and spec.method == "local" and spec.node == "system" and shutil.which("node") is None:
                issues.append(
                    Issue(
                        "warning",
                        "Node.js functions need `node` on PATH on this machine (https://nodejs.org/en/download), "
                        "or set options.deploy.node: bundle to download it at deploy.",
                        "provider.options.deploy.node",
                    )
                )
            if node and spec.method == "ssh" and spec.node == "system":
                issues.append(
                    Issue(
                        "warning",
                        f"the remote host must already have Node.js ({config.provider.runtime}) on PATH. "
                        "Set options.deploy.node: bundle to ship the Node.js binary, or method: docker.",
                        "provider.options.deploy.node",
                    )
                )
            running = f"python{sys.version_info.major}.{sys.version_info.minor}"
            if not node and spec.method == "local" and spec.python == "system" and config.provider.runtime != running:
                issues.append(
                    Issue(
                        "warning",
                        f"the host runs with this interpreter ({running}), not {config.provider.runtime}. "
                        "Use the same Python for `pskit deploy` and the functions, or set "
                        "options.deploy.python: bundle.",
                        "provider.runtime",
                    )
                )
            if spec.method == "ssh" and spec.python == "system":
                issues.append(
                    Issue(
                        "warning",
                        f"the remote host must already have {spec.runtime} on PATH. "
                        "Set options.deploy.python: bundle to ship a portable interpreter, or method: docker.",
                        "provider.options.deploy.python",
                    )
                )
            bind = str(options.get("host") or "127.0.0.1")
            if spec.method in ("ssh", "docker") and bind in ("127.0.0.1", "localhost"):
                issues.append(
                    Issue(
                        "warning",
                        "the host binds to 127.0.0.1 on the target. Set options.host: 0.0.0.0 to accept "
                        "LAN traffic, or keep 127.0.0.1 and reach it through an SSH tunnel.",
                        "provider.options.host",
                    )
                )
            if spec.install == "systemd" and not spec.sudo:
                issues.append(
                    Issue(
                        "warning",
                        "systemd units are written to /etc/systemd/system; set options.deploy.sudo: true "
                        "unless the SSH user is root.",
                        "provider.options.deploy.sudo",
                    )
                )
        if spec is not None:
            try:
                self._services(config, Path("."))
            except ValueError as exc:
                issues.append(Issue("error", str(exc), "provider.options.services"))
            for key, res in sorted(config.resources.items()):
                try:
                    self._driver(key, res, Path("."), spec)
                except ValueError as exc:
                    issues.append(Issue("error", str(exc), f"resources.{key}"))
                if res.type in DRIVERS:
                    bad_name = _safe_name(res.native_name(key), res.type)
                    if bad_name:
                        issues.append(Issue("error", bad_name, f"resources.{key}.name"))
        for name, fn in config.functions.items():
            for ev in fn.events_of("http"):
                if ev.auth != "none":
                    issues.append(
                        Issue(
                            "error",
                            f"auth `{ev.auth}` is not enforced on-premises; use auth: none and check tokens in the handler",
                            f"functions.{name}",
                        )
                    )
            for ev in fn.events_of("schedule"):
                if ev.cron:
                    zone = resolve_zone(ev.timezone)
                    if zone is None:
                        issues.append(
                            Issue(
                                "warning",
                                f"timezone {ev.timezone} needs the IANA database; `pskit deploy` vendors tzdata. "
                                "Until then this schedule is evaluated in UTC.",
                                f"functions.{name}",
                            )
                        )
                    try:
                        next_cron(ev.cron, datetime.now(timezone.utc))
                    except CronError as exc:
                        issues.append(Issue("error", str(exc), f"functions.{name}"))
            for kind, label in (("queue", "name"), ("topic", "name"), ("storage", "bucket")):
                for ev in fn.events_of(kind):
                    bad = _safe_name(getattr(ev, label), kind)
                    if bad:
                        issues.append(Issue("error", bad, f"functions.{name}"))
                    dead = getattr(ev, "dead_letter", None)
                    if dead:
                        bad_dead = _safe_name(dead, "dead_letter queue")
                        if bad_dead:
                            issues.append(Issue("error", bad_dead, f"functions.{name}"))
        dropped = _foreign_names(config.provider.terraform.extra)
        if dropped:
            issues.append(
                Issue(
                    "warning",
                    "on-premises deploy does not load other cloud providers, so these terraform.extra "
                    f"resources are omitted: {', '.join(dropped)}. Move a replacement under "
                    "providers.onprem.terraform.extra, or keep this file on its original provider.",
                    "provider.terraform.extra",
                )
            )
        backend = config.provider.state.backend
        if backend in ("s3", "gcs", "azurerm"):
            issues.append(
                Issue(
                    "warning",
                    f"state backend `{backend}` still points at a cloud. On a machine without that backend, "
                    "set provider.state.backend empty (or override it under providers.onprem) to keep state local.",
                    "provider.state",
                )
            )
        return issues

