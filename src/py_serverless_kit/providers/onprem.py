def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def _join_dir(base: str, child: str, posix: bool) -> str:
    if posix or "/" in base:
        return base.rstrip("/").rstrip("\\") + "/" + child
    return str(Path(base) / child)


def service_bucket(driver: Dict[str, Any], bucket: str) -> Dict[str, Any]:
    """``driver`` (a storage resource's binding) pointed at another ``bucket`` on the same service."""
    use = str(driver.get("use") or "builtin")
    if use == "builtin":
        return dict(driver)
    if use == "directory":
        raise ValueError(
            "a `directory` storage resource is one folder, not a service with buckets; "
            "drop `bucket` from the event or give the resource the builtin or an s3 driver"
        )
    return {**driver, ("container" if use == "azure_blob" else "bucket"): bucket}


def _safe_name(value: str, what: str) -> Optional[str]:
    text = str(value)
    if not text or text in (".", "..") or "/" in text or "\\" in text:
        return f"invalid {what} name {value!r}"
    return None


class OnPremProvider(Provider):
    name = "onprem"
    display_name = "On-premises"
    tier = "experimental"
    terraform_source = "terraform.io/builtin/terraform"
    default_region = "local"
    capabilities = frozenset({HTTP, SCHEDULE, QUEUE, STORAGE, TOPIC, SMTP})
    max_name_length = 63
    runtimes = {f"python3.{minor}": f"python3.{minor}" for minor in (9, 10, 11, 12, 13, 14)}
    # Node.js functions run in a `node` worker process driven by the (Python) host.
    node_runtimes = {f"nodejs{major}": f"nodejs{major}" for major in (18, 20, 22, 24)}
    vendor_dependencies = True
    # Zoneinfo on Windows reads this package. It is pure data and is imported
    # by the stdlib, so the host can honour schedule timezones without a system copy.
    extra_requirements = ["tzdata"]
    max_timeout = 3600
    warn_on_embedded_workflow = False
    storage_service_buckets = True
    standalone_resources = True
    notes = (
        "Runs a long-lived Python process. Default `options.deploy.method` is `local` "
        "(this machine). `ssh` and `scp` pack one archive, copy it with OpenSSH, and "
        "restart the host (process or systemd) until `/__pskit/health` answers. "
        "`docker` builds an image that includes Python. A remote Docker host "
        "(`deploy.host` or `docker_host: ssh://`) asks for a `.pem` key, builds the "
        "image locally, installs Docker on the server when it is missing, then loads "
        "and runs the image and waits until it is healthy. "
        "`python: bundle` ships a portable CPython for hosts without Python. "
        "Node.js services (runtime nodejs18-24) run each function in a `node` worker driven by the host; "
        "`node: bundle` ships the Node.js binary. "
        "HTTP, schedules, file-backed queues, directory storage, topics and embedded "
        "workflows all run in that process. Set provider.options.services.<kind> to "
        "`builtin` or `{use: directory, path: ...}`. `pskit remove` stops the process "
        "and leaves the data directory in place."
    )

