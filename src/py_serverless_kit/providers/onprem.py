"""On-premises provider.

``pskit deploy --provider onprem`` writes a self-contained host next to the
Terraform configuration and starts it with a built-in ``terraform_data``
provisioner (no cloud plugin, no extra broker to install).

``provider.options.deploy`` chooses where that host runs:

* ``local`` — this machine, same as earlier releases (the default)
* ``ssh`` or ``scp`` — pack one ``release.tar.gz``, copy it with ``scp``
  (OpenSSH, ``.pem`` when set), and start a process or a systemd unit.
  Apply restarts the unit and waits until ``/__pskit/health`` answers.
* ``docker`` — build an image that already contains Python and run a container.
  With ``host`` (or ``docker_host: ssh://...``) the image is built on this
  machine, copied over SSH with a ``.pem`` key, and started on the server.
  Docker is installed on that server first when it is not already there.
  Apply waits until the container answers ``/__pskit/health``.

When the target has no Python, set ``deploy.python: bundle`` (a portable
CPython is downloaded at apply and copied with the app) or ``method: docker``.

HTTP is served by that process. Schedule, queue, storage and topic triggers
use directories the host creates on startup (``use: builtin``). Point a service
at a directory you already run with ``use: directory`` and ``path``. Workflows
run on the embedded engine inside the same process, so they are not capped by
a cloud function timeout.

``terraform.extra`` resources that belong to another cloud (``aws_*``, ...) are
omitted: this configuration does not configure those providers. The warning
names each one.
"""

