"""IBM Cloud: Code Engine functions (HTTP endpoints)."""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from ..config.schema import ServiceConfig
from .base import HTTP, Issue, Provider, RenderContext
from .terraform_doc import TerraformDoc, escape, ref, tf_id

FUNCTION = "ibm_code_engine_function"
# Code Engine function CPU / memory combinations (vCPU, memory).
_SIZES: Tuple[Tuple[str, str, int], ...] = (
    ("0.125", "0.5G", 512),
    ("0.25", "1G", 1024),
    ("0.5", "2G", 2048),
    ("1", "4G", 4096),
)


def size_for(memory_mb: int) -> Tuple[str, str]:
    for cpu, mem, mb in _SIZES:
        if memory_mb <= mb:
            return cpu, mem
    return _SIZES[-1][0], _SIZES[-1][1]


class IbmProvider(Provider):
    name = "ibm"
    display_name = "IBM Cloud Code Engine"
    tier = "beta"
    terraform_source = "IBM-Cloud/ibm"
    terraform_version = ">= 1.70"
    default_region = "us-south"
    capabilities = frozenset({HTTP})
    max_name_length = 63
    runtimes = {"python3.11": "python-3.11"}
    vendor_dependencies = True
    max_timeout = 120
    notes = (
        "Every Code Engine function gets a public HTTPS endpoint; routes are matched by the pskit runtime. "
        "No schedule/queue/storage/topic triggers (the Terraform provider has no function event "
        "subscriptions). Code is uploaded inline as a base64 data URL, so keep bundles small or set "
        "options.code_reference to a code bundle image. Auth: set IC_API_KEY."
    )

    # ------------------------------------------------------------------ bundle
    def shim_files(self, config: ServiceConfig) -> Dict[str, str]:
        return {
            "__main__.py": (
                "# Generated by py-serverless-kit. Code Engine entrypoint: main(params)\n"
                "from py_serverless_kit.runtime.adapters.ibm import main  # noqa: F401\n"
            )
        }

    def provider_block(self, ctx: RenderContext) -> Dict[str, Any]:
        block: Dict[str, Any] = {"region": ctx.region}
        if ctx.opt("resource_group"):
            block["resource_group"] = ctx.opt("resource_group")
        return block

    def extra_validation(self, config: ServiceConfig) -> List[Issue]:
        issues: List[Issue] = []
        for name, fn in config.functions.items():
            for ev in fn.events_of("http"):
                if ev.auth != "none":
                    issues.append(
                        Issue(
                            "error",
                            f"auth `{ev.auth}` is not supported on Code Engine functions; "
                            "validate tokens in the handler",
                            f"functions.{name}",
                        )
                    )
            if config.memory_of(fn) > _SIZES[-1][2]:
                issues.append(
                    Issue("error", "Code Engine functions support at most 4096 MB", f"functions.{name}.memory")
                )
        return issues

    # ------------------------------------------------------------------ render
    def _project(self, doc: TerraformDoc, ctx: RenderContext) -> str:
        if ctx.opt("project_id"):
            return str(ctx.opt("project_id"))
        body: Dict[str, Any] = {"name": ctx.prefix}
        if ctx.opt("resource_group_id"):
            body["resource_group_id"] = ctx.opt("resource_group_id")
        return ref(doc.resource("ibm_code_engine_project", "project", body), "project_id")

    def render_resources(self, doc: TerraformDoc, ctx: RenderContext) -> None:
        cfg = ctx.config
        project = self._project(doc, ctx)
        code_ref = ctx.opt("code_reference") or 'data:text/plain;base64,${filebase64("${path.module}/artifact.zip")}'
        fn_out: Dict[str, Dict[str, Any]] = {}
        endpoint: Optional[str] = None
        for name, fn in ctx.function_items():
            cpu, mem = size_for(cfg.memory_of(fn))
            env = [
                {"type": "literal", "name": k, "value": escape(v)} for k, v in sorted(ctx.environment(name, fn).items())
            ]
            body: Dict[str, Any] = {
                "project_id": project,
                "name": ctx.physical_name(name),
                "runtime": self.runtime_id(cfg.runtime_of(fn)),
                "code_reference": code_ref,
                "code_binary": not ctx.opt("code_reference"),
                "code_main": "main",
                "scale_cpu_limit": cpu,
                "scale_memory_limit": mem,
                "scale_max_execution_time": cfg.timeout_of(fn),
                "managed_domain_mappings": fn.options.get("visibility", ctx.opt("visibility", "local_public")),
                "run_env_variables": env,
            }
            if fn.concurrency:
                body["scale_concurrency"] = fn.concurrency
            body.update({k: v for k, v in fn.options.items() if k != "visibility"})
            res = doc.resource(FUNCTION, name, body)
            out: Dict[str, Any] = {
                "id": ref(res, "function_id"),
                "url": ref(res, "endpoint"),
                "console": f"https://cloud.ibm.com/codeengine/project/{ctx.region}/{project}/functions",
            }
            if fn.events_of("http"):
                out["base_url"] = ref(res, "endpoint")
                endpoint = endpoint or ref(res, "endpoint")
            fn_out[name] = out
        wf_out = {n: {"id": ref(FUNCTION, tf_id(f"{n}-orchestrator"), "endpoint")} for n in cfg.workflows}
        doc.output(
            "pskit",
            {"functions": fn_out, "workflows": wf_out, "endpoint": endpoint},
            description="py-serverless-kit deployment summary",
        )
